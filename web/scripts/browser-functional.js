async (page) => {
 const ensure=(value,message)=>{if(!value)throw Error(message);};
 const originalStorage=await page.evaluate(()=>localStorage.getItem('study-desk-v1'));
 await page.waitForSelector('#lesson-status');
 ensure(await page.locator('#lesson-status').inputValue()==='mastered','Mastery did not survive reload');
 ensure(await page.locator('[data-save]').getAttribute('aria-pressed')==='true','Bookmark did not survive reload');
 await page.locator('.answer summary').first().click();
 ensure(await page.locator('.answer').first().getAttribute('open')!==null,'Answer did not open');
 await page.locator('#search').fill('Bayes');
 await page.getByRole('button',{name:'搜索',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route.startsWith('#/search'));
 const searchCount=await page.locator('.search-result').count();ensure(searchCount>=2,'Cross-course search failed');
 await page.locator('#course-filter').selectOption('eecs453');
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route.includes('course=eecs453'));
 const labels=await page.locator('.search-result > .eyebrow').allTextContents();
 ensure(labels.length>0&&labels.every(x=>x==='EECS 453'),'Course filter failed');
 await page.getByRole('link',{name:'ƒ 公式速查',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route==='#/formulas');
 ensure(await page.locator('.formula-card').count()===63,'Formula index incomplete');
 await page.getByRole('link',{name:'▤ 课程资料库',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route==='#/library');
 await page.locator('#category-filter').selectOption('伦理阅读');
 await page.waitForFunction(()=>document.querySelectorAll('.resource-row').length===1);
 ensure((await page.locator('.resource-row').innerText()).includes('Wrestling with Killer Robots'),'Unnamed reading not classified');
 const resourceURL=await page.locator('.resource-row a').getAttribute('href');
 const response=await page.request.get('http://127.0.0.1:3760'+resourceURL,{headers:{Range:'bytes=0-7'}});
 ensure(response.status()===206,'PDF resource failed');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#menu').click();
 ensure(await page.locator('body').getAttribute('class')==='menu-open','Mobile menu failed');
 await page.locator('.course-nav-item').filter({hasText:'MATH 465'}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route==='#/course/math465');
 ensure(!(await page.locator('body').getAttribute('class'))?.includes('menu-open'),'Menu did not close');
 await page.locator('.chapter-card').last().click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.route==='#/course/math465/recurrences');
 await page.screenshot({path:'output/playwright/mobile-viewport.png',animations:'disabled'});
 const mathBounds=await page.evaluate(()=>Array.from(document.querySelectorAll('.math')).map(el=>({container:el.clientWidth,scroll:el.scrollWidth,left:el.querySelector('.katex-display').getBoundingClientRect().left-el.getBoundingClientRect().left})));
 ensure(mathBounds.every(x=>x.left>=0),'Long formulas clipped at left');
 await page.locator('.skip').focus();
 await page.locator('.skip').click();
 ensure(page.url().endsWith('#/course/math465/recurrences'),'Skip link broke route');
 await page.evaluate(value=>{if(value===null)localStorage.removeItem('study-desk-v1');else localStorage.setItem('study-desk-v1',value);},originalStorage);
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://127.0.0.1:3760/');
 await page.waitForSelector('.hero');
 await page.screenshot({path:'output/playwright/home-final.png',fullPage:true});
 return {persistence:true,answers:true,searchCount,courseFilter:true,formulas:63,ethicsReading:true,pdfRange:true,mobileMenu:true,mathBounds,skipLink:true};
}
